const fs=require("fs");
const path=require("path");

const ROOT=path.join(
process.cwd(),
"packages",
"kvr",
"src",
"tools"
);

function ensure(dir){

if(!fs.existsSync(dir))
fs.mkdirSync(dir,{recursive:true});

}

function write(file,content){

fs.writeFileSync(
path.join(ROOT,file),
content,
"utf8"
);

console.log("✓",file);

}

ensure(ROOT);

[
"interfaces",
"contracts",
"dto",
"events",
"types"
].forEach(d=>ensure(path.join(ROOT,d)));

