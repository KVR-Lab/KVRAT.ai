param(
    [Parameter(Mandatory = $true)]
    [string]$ProjectName,

    [string]$Root = (Resolve-Path ".").Path,

    [switch]$Force
)

$ErrorActionPreference = "Stop"

$Project = $ProjectName.ToLower()
$ProjectPath = Join-Path $Root $Project

if ((Test-Path $ProjectPath) -and !$Force) {
    throw "Project already exists: $ProjectPath"
}

New-Item -ItemType Directory -Force -Path $ProjectPath | Out-Null

$Folders = @(
    "src",
    "src/controllers",
    "src/services",
    "src/modules",
    "src/entities",
    "src/dto",
    "src/config",
    "src/common",
    "src/tests",
    "scripts",
    "templates",
    "docs"
)

foreach ($Folder in $Folders) {
    New-Item `
        -ItemType Directory `
        -Path (Join-Path $ProjectPath $Folder) `
        -Force | Out-Null
}

$PackageJson = @"
{
  "name": "$Project",
  "version": "1.0.0",
  "private": true,
  "scripts": {
    "build": "nest build",
    "start": "nest start",
    "start:dev": "nest start --watch",
    "test": "jest"
  }
}
"@

$Readme = @"
# $ProjectName

Generated by KVR Project Generator.

## Structure

- src
- scripts
- templates
- docs

"@

$GitIgnore = @"
node_modules
dist
coverage
.env
"@

[System.IO.File]::WriteAllText(
    (Join-Path $ProjectPath "package.json"),
    $PackageJson,
    [System.Text.UTF8Encoding]::new($false)
)

[System.IO.File]::WriteAllText(
    (Join-Path $ProjectPath "README.md"),
    $Readme,
    [System.Text.UTF8Encoding]::new($false)
)

[System.IO.File]::WriteAllText(
    (Join-Path $ProjectPath ".gitignore"),
    $GitIgnore,
    [System.Text.UTF8Encoding]::new($false)
)

Write-Host ""
Write-Host "========================================="
Write-Host "      Project Generated Successfully"
Write-Host "========================================="
Write-Host "Project : $ProjectName"
Write-Host "Path    : $ProjectPath"
Write-Host ""
Write-Host "[OK] Folders created"
Write-Host "[OK] package.json"
Write-Host "[OK] README.md"
Write-Host "[OK] .gitignore"